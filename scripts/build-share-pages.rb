#!/usr/bin/env ruby
# Writes one page per post, at /blog/<id>/, and keeps a stub at /blog/posts/<id>/
# for links written before each post had a page of its own.
#
# The article used to be a single page, /blog/post.html?id=<id>, reached through
# those stubs: the card opened the stub, the stub handed the reader on with a
# meta refresh, so the address changed under the reader mid-click and the screen
# went dark on the way. A post now has a page of its own, built from
# blog/post.html, and a card opens it in one navigation.
#
# Each page also carries the post's front matter as Open Graph and Twitter tags.
# The article's own <head> cannot: JavaScript fills it in once the Markdown has
# loaded, and X, LinkedIn, Facebook, WeChat and QQ run no script.
require 'json'
require 'cgi'
require 'date'
require 'fileutils'

SITE = 'https://ammelsayed.pages.dev' # the host these links are shared from
BLOG_DIR = File.expand_path('../blog', __dir__)
SHELL_PATH = File.join(BLOG_DIR, 'post.html')
# `blog/post.html` is also served at `blog/post`, so a directory of that name
# would sit on the article's own address. The legacy stubs live here instead.
LEGACY_DIR = File.join(BLOG_DIR, 'posts')
INDEX_PATH = File.expand_path('../data/blogs.generated.json', __dir__)
# Written into every page this script produces, so a page whose post has gone
# can be recognised as ours and removed.
MARKER = '<!-- generated by scripts/build-share-pages.rb -->'.freeze
# Names that are already a page or a directory of the site. `post` is
# `blog/post.html`, which is also served at `blog/post`, and `post.html` /
# `index.html` are files in `blog/`, so a directory of either name would sit on
# something that already exists and `mkdir_p` would stop the build.
RESERVED_IDS = %w[post index posts post.html index.html].freeze
# An id names a directory on disk and a path in the site, so it is restricted to
# what a filename may hold. Without this, `..` would write a page over the site's
# own front page, and a `/` would put it outside `blog/` altogether.
ID_PATTERN = /\A[A-Za-z0-9][A-Za-z0-9._-]*\z/.freeze

def replace_once(page, needle, value, what)
  unless page.include?(needle)
    abort "Failing: #{what} is no longer in blog/post.html; the generator needs updating."
  end
  page.sub(needle, value)
end

# The path a page for this id is written to, with the id's own characters
# checked twice: once as a name, once as a path that has to stay inside root.
# The path is then checked for links, because a link is followed by every write
# that comes after this check.
def page_dir!(root, id, generated: false)
  unless id.match?(ID_PATTERN)
    warn "Failing: \"#{id}\" cannot be a post id; it is used as a directory name."
    exit 1
  end
  dir = File.join(root, id)
  page = File.join(dir, 'index.html')
  if File.symlink?(dir) || File.symlink?(page)
    warn "Failing: #{dir} is a link; a generated page cannot be written through it."
    exit 1
  end
  unless File.expand_path(dir).start_with?("#{File.expand_path(root)}/")
    warn "Failing: \"#{id}\" resolves to #{dir}, outside #{root}."
    exit 1
  end
  # `blog/` holds pages this script does not own, and a post can be given the
  # name of one. Ours carry the marker; a page without it is left alone rather
  # than replaced.
  if generated && File.exist?(page) && !File.read(page).include?(MARKER)
    warn "Failing: #{page} was not generated by this script; move it out of the way first."
    exit 1
  end
  dir
end

# A date on its own is not a datetime, and `article:published_time` is one.
# The front matter's date becomes the start of that day in UTC; a value that is
# not a real date is left out, because a wrong date is worse than none.
def published_time(date)
  return '' unless date.match?(/\A\d{4}-\d{2}-\d{2}\z/)
  "#{Date.iso8601(date).strftime('%Y-%m-%d')}T00:00:00Z"
rescue Date::Error, ArgumentError
  ''
end

unless File.exist?(INDEX_PATH)
  warn "Failing: #{INDEX_PATH} is missing; run scripts/build-blog-index.rb first."
  exit 1
end
unless File.exist?(SHELL_PATH)
  warn "Failing: #{SHELL_PATH} is missing; the article pages are built from it."
  exit 1
end

posts = JSON.parse(File.read(INDEX_PATH))
ids = posts.map { |post| post['id'].to_s }
# Every id is checked before anything is written or removed: found halfway
# through the run, a bad one would leave pages already replaced or deleted.
ids.each do |id|
  page_dir!(BLOG_DIR, id, generated: true)
  page_dir!(LEGACY_DIR, id)
end
shell = File.read(SHELL_PATH)

conflicting = ids & RESERVED_IDS
unless conflicting.empty?
  warn "Failing: #{conflicting.join(', ')} cannot be a post id; its page would sit on a page of the site."
  exit 1
end

# A post hidden with `show: false`, or deleted, drops out of the index. Its pages
# would otherwise stay behind, carrying metadata for an article that is gone.
# Under blog/posts/ every directory is ours, so any one that is not in the index
# goes. At the top of blog/ the site's own directories live too, so only a page
# carrying the marker is removed: the settings editor keeps sources as files,
# and those are never touched.
def remove_stale(root, dirs, ids, require_marker)
  dirs.each do |path|
    next unless File.directory?(path)
    next if ids.include?(File.basename(path))
    if require_marker
      page = File.join(path, 'index.html')
      next unless File.exist?(page) && File.read(page).include?(MARKER)
    end
    FileUtils.rm_rf(path)
  end
end

FileUtils.mkdir_p(LEGACY_DIR)
blog_dirs = Dir.glob(File.join(BLOG_DIR, '*')).reject { |path| File.basename(path) == 'posts' }
remove_stale(BLOG_DIR, blog_dirs, ids, true)
remove_stale(LEGACY_DIR, Dir.glob(File.join(LEGACY_DIR, '*')), ids, false)

posts.each do |post|
  id = post['id'].to_s
  title = CGI.escapeHTML(post['title'].to_s)
  description = CGI.escapeHTML(post['description'].to_s.gsub(/\s+/, ' ').strip)
  date = post['date'].to_s
  image = post['image'].to_s.strip
  # Anything that is not already an absolute or protocol-relative url is a path on
  # this site, with or without a leading slash; a preview reads it from the page's
  # own directory otherwise.
  image = "#{SITE}/#{image.delete_prefix('/')}" unless image.empty? || image.match?(%r{\A(?:https?:)?//}i)
  url = "#{SITE}/blog/#{id}/"

  # The article page: blog/post.html with its own head and its own id. The
  # script it loads reads that id, so nothing has to choose the post at runtime.
  page = shell.dup
  page = replace_once(page, '<title>Blog Post</title>',
                      %(<title>#{title} | Blog</title>\n    <meta name="description" content="#{description}">\n    <link rel="canonical" href="#{CGI.escapeHTML(url)}">),
                      'the placeholder <title>')
  page = replace_once(page, '<meta property="og:title" content="Blog Post" id="og-title">',
                      %(<meta property="og:title" content="#{title}" id="og-title">),
                      'the og:title tag')
  page = replace_once(page, '<meta property="og:description" content="Blog Post" id="og-description">',
                      %(<meta property="og:description" content="#{description}" id="og-description">),
                      'the og:description tag')
  page = replace_once(page, '<meta property="og:url" content="">',
                      %(<meta property="og:url" content="#{CGI.escapeHTML(url)}">),
                      'the og:url tag')
  page = replace_once(page, '<meta property="og:image" content="">',
                      %(<meta property="og:image" content="#{image.empty? ? '' : CGI.escapeHTML(image)}">),
                      'the og:image tag')
  # The date the article was published, written the way a reader's browser and a
  # crawler both read it. The tag is left out rather than sent empty when a post
  # has no usable date: an empty value is a wrong date, not an absent one.
  published = published_time(date)
  page = replace_once(page, '<meta property="og:type" content="article">',
                      %(<meta property="og:type" content="article">\n    ) +
                      (published.empty? ? '' : %(<meta property="article:published_time" content="#{published}">)),
                      'the og:type tag')
  # The id reaches the script as a JavaScript string literal. JSON's string
  # syntax is a JavaScript string, and the `<` is escaped because the literal
  # sits inside a script element, where it would otherwise end the document's
  # tag early.
  id_literal = JSON.generate(id).gsub('<', '\u003c')
  # The tag is matched by its opening characters, so the attributes it carries
  # (its `onerror` among them) stay as they are on every page.
  page = replace_once(page, '<script src="/styles/post.js"',
                      %(<script>window.POST_ID = #{id_literal};</script>\n    <script src="/styles/post.js"),
                      'the post script tag')
  page = page.sub('</html>', "#{MARKER}\n</html>")

  FileUtils.mkdir_p(page_dir!(BLOG_DIR, id, generated: true))
  File.write(File.join(BLOG_DIR, id, 'index.html'), page)

  # The legacy address, kept for links that were already shared. It is small and
  # carries the same metadata, so an old share still previews; a reader who
  # follows it lands on the post's page.
  stub = <<~HTML
    <!DOCTYPE html>
    <html lang="en">
    <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>#{title}</title>
    <meta name="description" content="#{description}">
    <link rel="canonical" href="#{CGI.escapeHTML(url)}">
    <meta property="og:type" content="article">
    <meta property="og:site_name" content="A.M.M. Elsayed">
    <meta property="og:title" content="#{title}">
    <meta property="og:description" content="#{description}">
    <meta property="og:url" content="#{CGI.escapeHTML(url)}">
    #{image.empty? ? '' : %(<meta property="og:image" content="#{CGI.escapeHTML(image)}">)}
    #{published.empty? ? '' : %(<meta property="article:published_time" content="#{published}">)}
    <meta name="twitter:card" content="#{image.empty? ? 'summary' : 'summary_large_image'}">
    <meta name="twitter:title" content="#{title}">
    <meta name="twitter:description" content="#{description}">
    #{image.empty? ? '' : %(<meta name="twitter:image" content="#{CGI.escapeHTML(image)}">)}
    <meta http-equiv="refresh" content="0; url=/blog/#{id}/">
    <style>
    body { margin: 0; padding: 15vh 24px; font: 16px/1.6 system-ui, sans-serif; background: #101010; color: #e5e5e5; text-align: center; }
    a { color: #ffcc00; }
    </style>
    </head>
    <body>
    <p><a href="/blog/#{id}/">#{title}</a></p>
    <script>location.replace('/blog/#{id}/' + location.hash);</script>
    #{MARKER}
    </body>
    </html>
  HTML

  FileUtils.mkdir_p(page_dir!(LEGACY_DIR, id))
  File.write(File.join(LEGACY_DIR, id, 'index.html'), stub)
end

puts "Generated #{posts.length} article page(s) under #{BLOG_DIR}/<id>/ and their legacy stubs."
