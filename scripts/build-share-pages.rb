#!/usr/bin/env ruby
# Writes one page per post, at blog/<id>.html, and nothing else into blog/.
#
# The page used to sit in a directory, blog/<id>/index.html, and a directory
# answers only at /blog/<id>/: the clean address was a redirect, so the click
# looked like two and the address in the bar changed under the reader. An
# .html file answers at its own path with the extension left off, on both hosts
# that serve this site, and that is the address written everywhere else.
#
# The page is committed, not built at deploy time, because this site is
# published twice: GitHub Pages runs these scripts while it builds, and
# Cloudflare Pages publishes the repository exactly as it stands. The workflow
# that commits the JSON runs this as well, so publishing a post is still writing
# one .md and letting the bot write the page beside it.
#
# Each page also carries the post's front matter as Open Graph and Twitter tags.
# The article's own <head> cannot: JavaScript fills it in once the Markdown has
# loaded, and X, LinkedIn, Facebook, WeChat and QQ run no script.
require 'json'
require 'cgi'
require 'date'
require 'fileutils'
require 'securerandom'
require_relative 'lib/post_id'

SITE = 'https://ammelsayed.pages.dev' # the host these links are shared from
BLOG_DIR = File.expand_path('../blog', __dir__)
SHELL_PATH = File.join(BLOG_DIR, 'post.html')
INDEX_PATH = File.expand_path('../data/blogs.generated.json', __dir__)
# Written into every page this script produces, so a page whose post has gone
# can be recognised as ours and removed.
MARKER = '<!-- generated by scripts/build-share-pages.rb -->'.freeze

def replace_once(page, needle, value, what)
  unless page.include?(needle)
    abort "Failing: #{what} is no longer in blog/post.html; the generator needs updating."
  end
  page.sub(needle, value)
end

# The front matter keeps the day the post went up; the tag wants an instant.
# The day is read however it was written - `1999-9-09` is a day like any other -
# but it has to be a day: `Date.parse` fills in what a value leaves out and rolls
# an impossible one forward, so it would answer an empty date with today and
# `2026-02-31` with the third of March. `strptime` refuses both instead, and the
# post is named in a warning rather than losing the tag in silence.
def published_time(value)
  date = Date.strptime(value.to_s.strip, '%Y-%m-%d')
  "#{date.strftime('%Y-%m-%d')}T00:00:00Z"
rescue Date::Error, ArgumentError, TypeError
  nil
end

unless File.exist?(INDEX_PATH)
  warn "Failing: #{INDEX_PATH} is missing; run scripts/build-blog-index.rb first."
  exit 1
end
unless File.exist?(SHELL_PATH)
  warn "Failing: #{SHELL_PATH} is missing; the article pages are built from it."
  exit 1
end

posts = JSON.parse(File.read(INDEX_PATH))
ids = posts.map { |post| post['id'].to_s }
shell = File.read(SHELL_PATH)

ids.each do |id|
  problem = PostId.problem(id)
  next unless problem
  warn "Failing: #{id.inspect} #{problem}."
  exit 1
end

FileUtils.mkdir_p(BLOG_DIR)

posts.each do |post|
  id = post['id'].to_s
  title = CGI.escapeHTML(post['title'].to_s)
  description = CGI.escapeHTML(post['description'].to_s.gsub(/\s+/, ' ').strip)
  date = post['date'].to_s
  image = post['image'].to_s.strip
  # Anything that is not already an absolute or protocol-relative url is a path on
  # this site, with or without a leading slash; a preview reads it from the page's
  # own directory otherwise.
  image = "#{SITE}/#{image.delete_prefix('/')}" unless image.empty? || image.match?(%r{\A(?:https?:)?//}i)
  url = "#{SITE}/blog/#{id}"
  published = published_time(date)
  warn "Skipping article:published_time on #{id}: #{date.inspect} is not a date." if published.nil? && !date.empty?

  # The article page: blog/post.html with its own head and its own id. The
  # script it loads reads that id, so nothing has to choose the post at runtime.
  page = shell.dup
  page = replace_once(page, '<title>Blog Post</title>',
                      %(<title>#{title} | Blog</title>\n    <meta name="description" content="#{description}">\n    <link rel="canonical" href="#{CGI.escapeHTML(url)}">),
                      'the placeholder <title>')
  page = replace_once(page, '<meta property="og:title" content="Blog Post" id="og-title">',
                      %(<meta property="og:title" content="#{title}" id="og-title">),
                      'the og:title tag')
  page = replace_once(page, '<meta property="og:description" content="Blog Post" id="og-description">',
                      %(<meta property="og:description" content="#{description}" id="og-description">),
                      'the og:description tag')
  page = replace_once(page, '<meta property="og:url" content="">',
                      %(<meta property="og:url" content="#{CGI.escapeHTML(url)}">),
                      'the og:url tag')
  # The shell holds one empty og:image tag; it is replaced by the post's image,
  # the date it went up, and the Twitter card, which the crawlers that read
  # twitter:* want spelled out rather than borrowed from Open Graph. The
  # og:image tag stays even when the post names no image: the article script
  # writes the first image of the body into it once the Markdown has loaded, and
  # it reads that element without checking for it.
  tags = []
  tags << %(<meta property="og:image" content="#{CGI.escapeHTML(image)}">)
  tags << %(<meta property="article:published_time" content="#{published}">) if published
  tags << %(<meta name="twitter:card" content="#{image.empty? ? 'summary' : 'summary_large_image'}">)
  tags << %(<meta name="twitter:title" content="#{title}">)
  tags << %(<meta name="twitter:description" content="#{description}">)
  tags << %(<meta name="twitter:image" content="#{CGI.escapeHTML(image)}">) unless image.empty?
  page = replace_once(page, '<meta property="og:image" content="">', tags.join("\n    "),
                      'the og:image tag')
  page = replace_once(page, '<script src="/styles/post.js"></script>',
                      %(<script>window.POST_ID = "#{id}";</script>\n    <script src="/styles/post.js"></script>),
                      'the post script tag')
  page = page.sub('</html>', "#{MARKER}\n</html>")

  # Written beside the page and moved onto it. The name it is written under is a
  # new one every time, so nothing that was there is opened for writing. Neither
  # name may be a link: `blog` is committed, so a write that followed one would
  # land in whatever it points at and be committed there. A page the generator
  # did not write is someone's file at the post's address, and it is not replaced
  # either.
  path = File.join(BLOG_DIR, "#{id}.html")
  abort "Failing: #{path} is a link, and it would be written through." if File.symlink?(path)
  abort "Failing: #{path} was not written by this script, and it is not replaced." if File.exist?(path) && !File.read(path).include?(MARKER)
  partial = File.join(BLOG_DIR, ".#{id}.html.#{SecureRandom.hex(8)}.partial")
  File.write(partial, page)
  File.rename(partial, path)
end

# A post hidden with `show: false`, or deleted, drops out of the index. Its page
# would otherwise stay beside it, carrying metadata for an article that is gone.
# Only a page carrying the marker is removed: the listing and the shell are .html
# in this folder too, and they are never ours to delete.
Dir.glob(File.join(BLOG_DIR, '*.html')).each do |path|
  next if ids.include?(File.basename(path, '.html'))
  next if File.symlink?(path)
  File.delete(path) if File.read(path).include?(MARKER)
end

puts "Generated #{posts.length} article page(s) at #{BLOG_DIR}/<id>.html"
